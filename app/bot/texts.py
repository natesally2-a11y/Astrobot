def subscription_status_text(
    plan: str, expires_at: str | None, asked_today: int, limit: int
) -> str:
    if plan == "free":
        return (
            "Подписка: <b>Free</b>\n"
            f"Бесплатных вопросов сегодня: {asked_today}/{limit}\n\n"
            "Откройте все возможности — обновитесь до Pro или Oracle."
        )
    expires = expires_at or "—"
    label = "Pro" if plan == "pro" else "Космический Оракул"
    return f"Подписка: <b>{label}</b>\nДействует до: {expires}"
